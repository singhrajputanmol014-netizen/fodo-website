#!/usr/bin/env python3
"""Builds js/reviews.js from data/reviews.csv. Run from the project root: python3 scripts/build_reviews.py

CSV columns:
  record_id, business_name, category, business_type, area, country, services ("A; B"), business_goal,
  review_text, rating (1-5), review_date (YYYY-MM), review_source (Google | WhatsApp | Email | Direct),
  record_type ("client" | "sample"), is_verified_client (true/false), has_written_permission (true/false)

A row is published as a VERIFIED client review only when ALL of these hold:
  record_type == "client", is_verified_client == true, has_written_permission == true,
  and business_name + review_text are present.
Every other row is exported with demo:true / verified:false, and the Reviews page never shows those in live mode.
"""
import csv, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data", "reviews.csv")
OUT = os.path.join(ROOT, "js", "reviews.js")
REQUIRED = ["record_id", "business_name", "category", "area", "review_text", "record_type", "is_verified_client", "has_written_permission"]
TRUE = {"true", "yes", "y", "1"}

def clean(v):
    return " ".join(str(v or "").split())

def main():
    rows, warnings, seen = [], [], set()
    if os.path.exists(SRC):
        reader = csv.DictReader(open(SRC, encoding="utf-8-sig", newline=""))
        missing = [c for c in REQUIRED if c not in (reader.fieldnames or [])]
        if missing:
            sys.exit(f"data/reviews.csv is missing columns: {', '.join(missing)}")
        for n, r in enumerate(reader, start=2):
            r = {k: clean(v) for k, v in r.items() if k}
            rid = r.get("record_id") or f"ROW-{n}"
            if rid in seen:
                warnings.append(f"line {n}: duplicate record_id {rid} skipped"); continue
            seen.add(rid)
            if not r.get("business_name") or not r.get("review_text"):
                warnings.append(f"line {n}: {rid} has no business_name or review_text, skipped"); continue
            verified = (r.get("record_type", "").lower() == "client"
                        and r.get("is_verified_client", "").lower() in TRUE
                        and r.get("has_written_permission", "").lower() in TRUE)
            try:
                rating = int(r.get("rating") or 0)
            except ValueError:
                rating = 0; warnings.append(f"line {n}: {rid} rating '{r.get('rating')}' is not a number")
            item = {"id": rid, "name": r["business_name"], "cat": r.get("category") or "Other", "type": r.get("business_type", ""),
                    "area": r.get("area") or "", "text": r["review_text"],
                    "services": [s.strip() for s in r.get("services", "").split(";") if s.strip()],
                    "verified": verified, "demo": not verified}
            if 1 <= rating <= 5: item["rating"] = rating
            if r.get("review_date"): item["date"] = r["review_date"]
            if r.get("review_source"): item["source"] = r["review_source"]
            rows.append(item)
    live = sum(1 for x in rows if x["verified"])
    head = ("/* FODO reviews data: GENERATED by scripts/build_reviews.py from data/reviews.csv. Do not edit by hand.\n"
            f"   {len(rows)} records: {live} verified client reviews, {len(rows) - live} unverified samples.\n"
            "   Only rows with verified:true are shown when config.js has reviewsMode: \"live\". */\n")
    open(OUT, "w", encoding="utf-8").write(head + "window.FODO_REVIEWS=" + json.dumps(rows, ensure_ascii=False) + ";\n")
    for w in warnings: print("WARN", w)
    print(f"js/reviews.js: {len(rows)} records ({live} verified, {len(rows) - live} samples)")

if __name__ == "__main__":
    main()
