#!/usr/bin/env node
/* Builds functions/_lib/knowledge.js (the FODO facts the AI may use) from js/config.js + js/data.js.
   Run after editing either file:  node scripts/build_llm_knowledge.js
   Keep the output small: every character is sent to the model on every chat turn. */
const fs = require("fs"), vm = require("vm"), path = require("path");
const root = path.resolve(__dirname, "..");
const ctx = { window: {}, document: { querySelector: () => null } };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, "js/config.js"), "utf8"), ctx);
vm.runInContext(
  fs.readFileSync(path.join(root, "js/data.js"), "utf8").replace("window.FODO_DATA = {};", "var FODO_DATA = {}; window.FODO_DATA = FODO_DATA;"),
  ctx
);
const C = ctx.window.FODO, D = ctx.window.FODO_DATA;
const one = (s) => String(s || "").replace(/\s+/g, " ").trim();
const first = (s) => one(s).split(/(?<=[.!?])\s/)[0];

const lines = [];
lines.push(`# FODO FACTS (the only business facts you may state)`);
lines.push(`Brand: ${C.brand}. Tagline: "${C.tagline}". Independent digital growth agency, New Delhi, India. Founder: ${C.founderName}.`);
lines.push(`Contact: WhatsApp/phone ${C.phoneDisplay}; email ${C.email}; address ${C.address}; Instagram ${C.instagramHandle}.`);
lines.push(`Founding Clients Programme: ${C.foundingSlotsTotal} partner slots, cohort ${C.foundingCohort}. Do not state how many are left.`);
lines.push(``);
lines.push(`## Services (${D.services.length})`);
D.services.forEach((s) => lines.push(`- ${s.name} (/services/#${s.slug}): ${first(s.problem)}`));
lines.push(``);
lines.push(`## Industries`);
D.industries.forEach((i) => lines.push(`- ${i.name} (/industries/#${i.slug}): channels ${i.channels.join(", ")}`));
lines.push(``);
lines.push(`## Growth System (6 stages)`);
lines.push(D.stages.map((s) => `${s.n} ${s.name}`).join(" > "));
lines.push(``);
lines.push(`## FAQ (official answers; reuse their meaning)`);
D.faqs.forEach((f) => lines.push(`Q: ${f.q}\nA: ${one(f.a)}`));
lines.push(``);
lines.push(`## Site pages you may link to`);
lines.push(`/services/ /industries/ /work/ /insights/ /resources/ /growth-score/ (self-assessment) /roi-calculator/ /fodo-challenge/ (4-round game) /marketing-quiz/ /about/ /faq/ /reviews/ /legal/ /contact/?mode=audit (Free Growth Audit) /contact/?mode=call (book a call)`);
lines.push(``);
lines.push(`## Honesty rules about FODO`);
lines.push(`- All case studies on the site are CONCEPT examples, not real clients. Never claim real client results, named clients, revenue figures or testimonials.`);
lines.push(`- Reviews page may show demo data. Do not quote reviews.`);
lines.push(`- No fixed price list. Never invent prices, packages, discounts or guarantees. Say pricing is scoped in a custom growth plan after a free audit.`);
lines.push(`- Ad spend is paid by the client from their own accounts. Nobody can guarantee results.`);
lines.push(`- Discounts are currently not offered.`);

const text = lines.join("\n");
const out = `/* AUTO-GENERATED by scripts/build_llm_knowledge.js — do not edit by hand. */\nexport const KNOWLEDGE = ${JSON.stringify(text)};\nexport const SITE = ${JSON.stringify({ url: C.siteUrl, whatsapp: C.whatsappNumber, email: C.email })};\n`;
fs.writeFileSync(path.join(root, "functions/_lib/knowledge.js"), out);
console.log(`knowledge.js written: ${text.length} chars (~${Math.round(text.length / 4)} tokens)`);
